// Adding a new character only requires adding one data entry here and placing its art
// in assets/art/characters/<id>_portrait.jpg & assets/art/characters/sprites/<id>_{front,side,back}.png.
// SharedArt/characters is referenced read-only in place (never renamed, moved, or deleted).

/**
 * Convention-based art resolver: derives all runtime art paths from character ID alone.
 * @param {string} id
 * @param {boolean} hasSpriteArt
 * @param {string} [artIdOverride] Optional override for alternate skins (e.g. 'miller_wolf')
 */
export function resolveCharacterArt(id, hasSpriteArt = true, artIdOverride = null) {
  if (!hasSpriteArt) {
    return { portrait: null, splash: null, refSheet: null, sprites: null };
  }
  const key = artIdOverride || id;
  return {
    portrait: `assets/art/characters/${key}_portrait.jpg`,
    splash: `assets/art/characters/${key}_splash.jpg`,
    refSheet: `assets/art/characters/${key}_ref.jpg`,
    sprites: {
      front: `assets/art/characters/sprites/${key}_front.png`,
      side: `assets/art/characters/sprites/${key}_side.png`,
      back: `assets/art/characters/sprites/${key}_back.png`,
    },
  };
}

